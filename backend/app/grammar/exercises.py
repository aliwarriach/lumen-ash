"""Practice exercises for every A1 grammar pattern. Fixed content, the same for every learner, and
checked by plain rules: no AI is involved anywhere in practice.

Three kinds:
  choice  pick the right word (or the right sentence) from a few options
  fill    type the missing word; the verb or word to use is given in brackets
  order   put word tiles in the right order; the English sentence is shown

Every exercise has a hint (shown on request, before answering) and a one-line reason (shown after
answering). `BOOK_CHAPTER` is the Netzwerk neu A1 chapter where each pattern is first taught, so
practice can follow the course. Like the catalogue, all of this should be checked by a teacher.
"""

from dataclasses import dataclass
from enum import StrEnum

from app.grammar.catalog import PatternKey
from app.review.grading import normalize  # the same rule as review answers, and the app


class ExerciseKind(StrEnum):
    CHOICE = "choice"
    FILL = "fill"
    ORDER = "order"


@dataclass(frozen=True)
class Exercise:
    id: str
    kind: ExerciseKind
    # choice/fill: the German sentence with ___ for the gap (or a question for sentence choices);
    # order: the English sentence to build.
    prompt: str
    # Accepted answers; the first is the one shown. For order: whole sentences, without the final
    # full stop or question mark.
    answers: tuple[str, ...]
    hint: str
    why: str
    english: str | None = None  # translation of a choice/fill sentence
    options: tuple[str, ...] = ()  # choice only
    exact_case: bool = False  # capital letters must match (fill only; choices always do)
    end: str = "."  # order only: the punctuation shown after the tiles

    @property
    def tiles(self) -> tuple[str, ...]:
        return tuple(self.answers[0].split(" ")) if self.kind is ExerciseKind.ORDER else ()


def _choice(
    id: str, prompt: str, options: tuple[str, ...], answer: str, hint: str, why: str,
    english: str | None = None,
) -> Exercise:  # fmt: skip
    return Exercise(id, ExerciseKind.CHOICE, prompt, (answer,), hint, why, english, options)


def _fill(
    id: str, prompt: str, answers: tuple[str, ...], hint: str, why: str,
    english: str | None = None, exact_case: bool = False,
) -> Exercise:  # fmt: skip
    return Exercise(
        id, ExerciseKind.FILL, prompt, answers, hint, why, english, exact_case=exact_case
    )


def _order(
    id: str, english: str, sentence: str, hint: str, why: str,
    also: tuple[str, ...] = (), end: str = ".",
) -> Exercise:  # fmt: skip
    return Exercise(id, ExerciseKind.ORDER, english, (sentence, *also), hint, why, end=end)


