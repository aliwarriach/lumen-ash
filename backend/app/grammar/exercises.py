def is_correct(exercise: Exercise, given: str) -> bool:
    """Plain rules, mirrored in app/src/features/grammar/practice.ts for instant feedback."""
    answer = normalize(given)
    accepted = [normalize(a) for a in exercise.answers]
    if exercise.kind is ExerciseKind.CHOICE or exercise.exact_case:
        return answer in accepted
    return answer.casefold() in {a.casefold() for a in accepted}
