from datetime import datetime
from typing import Annotated
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

from app.core.types import UtcDatetime
from app.grammar.catalog import MistakeCategory, PatternKey
from app.review.models import CardType
from app.vocabulary.forms import Article, VerbForms, WordKind
from app.vocabulary.models import WordStage

AnswerText = Annotated[str, StringConstraints(strip_whitespace=True, max_length=1000)]


class QueueWord(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: UUID
    kind: WordKind
    german: str
    article: Article | None
    plural: str | None
    plural_only: bool
    meaning_en: str
    meaning_ur: str | None
    example_sentence: str | None
    audio_url: str | None
    ipa: str | None
    verb_forms: VerbForms | None


class QueueMistake(BaseModel):
    id: UUID
    wrong: str
    correct: str
    category: MistakeCategory
    pattern_key: PatternKey | None
    pattern_title: str | None
    explanation: str | None


class QueueCard(BaseModel):
    card_id: UUID
    card_type: CardType
    is_new: bool
    due: UtcDatetime
    word: QueueWord | None = Field(description="Set for every card type except error_retry")
    mistake: QueueMistake | None = Field(description="Set for error_retry cards")


class QueueOut(BaseModel):
    cards: list[QueueCard]
    due_count: int = Field(description="Reviews due now (not counting new cards)")
    new_count: int = Field(description="New cards available today, within the daily limit")
    new_per_day: int
    next_due_at: UtcDatetime | None = Field(description="When the next review falls due after now")


class ReviewAnswer(BaseModel):
    text: AnswerText | None = None  # produce, sentence and error-retry cards
    article: Article | None = None  # article cards
    plural: AnswerText | None = None  # article cards


class ReviewIn(BaseModel):
    id: UUID = Field(description="Generated by the app; resending the same id is safe")
    card_id: UUID
    rating: Annotated[int, Field(ge=1, le=4)] = Field(description="1 Again, 2 Hard, 3 Good, 4 Easy")
    answer: ReviewAnswer = ReviewAnswer()
    # Plain datetime on input: the router rejects times without a timezone.
    reviewed_at: datetime | None = Field(
        default=None, description="When answered, for reviews done offline. Defaults to now."
    )
    duration_ms: Annotated[int, Field(ge=0, le=3_600_000)] | None = None


class ReviewOut(BaseModel):
    review_id: UUID
    duplicate: bool = Field(description="This id was already recorded; nothing changed")
    correct: bool
    checked: bool = Field(description="True if the server checked the answer itself")
    rating: int = Field(description="The rating applied (a wrong checked answer is always 1)")
    expected: str | None
    feedback: str | None
    due: UtcDatetime
    word_id: UUID | None
    mistake_id: UUID | None
    stage: WordStage | None = Field(description="The word's stage; null for mistake retries")
    stage_reason: str | None
    stage_changed: bool


class ReviewHistoryOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    card_type: CardType
    correct: bool
    checked: bool
    answer: str | None
    expected: str | None
    reviewed_at: UtcDatetime
