from datetime import datetime
from enum import StrEnum
from typing import Any
from uuid import UUID

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    SmallInteger,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import Base, OwnedMixin


class CardType(StrEnum):
    RECALL = "recall"  # German shown -> learner recalls the meaning (self-rated)
    PRODUCE = "produce"  # English shown -> learner types the German (checked)
    ARTICLE = "article"  # nouns: article and plural (checked)
    SENTENCE = "sentence"  # learner writes a fresh sentence with the word
    ERROR_RETRY = "error_retry"  # a logged mistake: learner writes the corrected version (checked)


def _card_type_enum() -> Enum:
    return Enum(
        CardType,
        native_enum=False,
        create_constraint=True,
        length=20,
        values_callable=lambda members: [m.value for m in members],
        name="card_type",
    )


# Every card and answer is about exactly one word or one logged mistake.
_ONE_SUBJECT = "num_nonnulls(word_id, mistake_id) = 1"


class ReviewCard(OwnedMixin, Base):
    """One way of practising one word (or retrying one mistake), scheduled with FSRS."""

    __tablename__ = "review_cards"
    __table_args__ = (
        UniqueConstraint("word_id", "card_type", name="uq_review_cards_word_type"),
        Index("ix_review_cards_user_due", "user_id", "due"),
        CheckConstraint(_ONE_SUBJECT, name="one_subject"),
    )

    word_id: Mapped[UUID | None] = mapped_column(ForeignKey("vocab_words.id", ondelete="CASCADE"))
    mistake_id: Mapped[UUID | None] = mapped_column(
        ForeignKey("mistakes.id", ondelete="CASCADE"), unique=True
    )
    card_type: Mapped[CardType] = mapped_column(_card_type_enum())
    # The full FSRS card (fsrs.Card.to_dict()). The columns below copy what we query on.
    fsrs: Mapped[dict[str, Any]] = mapped_column(JSONB)
    due: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    # fsrs.State: 1 learning, 2 review, 3 relearning
    state: Mapped[int] = mapped_column(SmallInteger)
    stability: Mapped[float | None]
    reps: Mapped[int] = mapped_column(default=0, server_default="0")
    lapses: Mapped[int] = mapped_column(default=0, server_default="0")
    last_review: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class ReviewLog(Base):
    """Every answer the learner gives. The evidence behind stages and progress."""

    __tablename__ = "review_logs"
    __table_args__ = (
        Index("ix_review_logs_user_reviewed", "user_id", "reviewed_at"),
        CheckConstraint(_ONE_SUBJECT, name="one_subject"),
    )

    # Generated by the app, so a retried upload of the same answer is recognised.
    id: Mapped[UUID] = mapped_column(primary_key=True)
    user_id: Mapped[UUID]
    card_id: Mapped[UUID] = mapped_column(
        ForeignKey("review_cards.id", ondelete="CASCADE"), index=True
    )
    word_id: Mapped[UUID | None] = mapped_column(
        ForeignKey("vocab_words.id", ondelete="CASCADE"), index=True
    )
    mistake_id: Mapped[UUID | None] = mapped_column(
        ForeignKey("mistakes.id", ondelete="CASCADE"), index=True
    )
    card_type: Mapped[CardType] = mapped_column(_card_type_enum())
    rating: Mapped[int] = mapped_column(SmallInteger)  # fsrs.Rating 1-4, after any override
    # Checked answers: was it right? Self-rated cards: rating >= Good.
    correct: Mapped[bool]
    # Whether `correct` came from the server checking the answer (True) or the learner (False).
    checked: Mapped[bool]
    answer: Mapped[str | None] = mapped_column(Text)
    expected: Mapped[str | None] = mapped_column(Text)
    duration_ms: Mapped[int | None]
    reviewed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
